param(
    [string]$Archive = '.tools/kemar/diffuse.zip',
    [string]$Output = 'src/spatial/data/kemarHorizontal.h'
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem
$expectedHash = 'a48e73137390626ef1e45d1de6a4d98530c6aa570e71b40f7c4442241ed5fa22'
if ((Get-FileHash -LiteralPath $Archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $expectedHash) {
    throw 'KEMAR archive SHA256 mismatch'
}
$zip = [IO.Compression.ZipFile]::OpenRead((Resolve-Path -LiteralPath $Archive))
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Bill Gardner and Keith Martin, Copyright 1994 MIT Media Laboratory.')
$lines.Add('// Diffuse-field KEMAR, horizontal plane, 44100 Hz stereo PCM16; see kemarAttribution.md.')
$lines.Add('// Generated by scripts/buildKemarTable.ps1; interleaved left/right, no normalization.')
$lines.Add('#pragma once')
$lines.Add('#include <array>')
$lines.Add('#include <cstdint>')
$lines.Add('namespace ahq::audio::data {')
$lines.Add('inline constexpr std::array<std::array<std::int16_t, 256>, 37> KEMAR_HORIZONTAL{{')
try {
    for ($angle = 0; $angle -le 180; $angle += 5) {
        $name = 'elev0/H0e{0:D3}a.wav' -f $angle
        $entry = $zip.GetEntry($name)
        if ($null -eq $entry) { throw "Missing $name" }
        $reader = [IO.BinaryReader]::new($entry.Open())
        try { $bytes = $reader.ReadBytes([int]$entry.Length) } finally { $reader.Dispose() }
        if ($bytes.Length -ne 556 -or [Text.Encoding]::ASCII.GetString($bytes, 0, 4) -ne 'RIFF' -or
            [Text.Encoding]::ASCII.GetString($bytes, 8, 4) -ne 'WAVE' -or
            [BitConverter]::ToUInt16($bytes, 20) -ne 1 -or
            [BitConverter]::ToUInt16($bytes, 22) -ne 2 -or
            [BitConverter]::ToUInt32($bytes, 24) -ne 44100 -or
            [BitConverter]::ToUInt16($bytes, 34) -ne 16 -or
            [Text.Encoding]::ASCII.GetString($bytes, 36, 4) -ne 'data' -or
            [BitConverter]::ToUInt32($bytes, 40) -ne 512) { throw "Unexpected WAV header: $name" }
        $lines.Add('    {{ // ' + $angle + ' degrees')
        for ($begin = 0; $begin -lt 256; $begin += 12) {
            $values = for ($sample = $begin; $sample -lt [Math]::Min($begin + 12, 256); $sample++) {
                $offset = 44 + 2 * $sample
                $unsigned = [int]$bytes[$offset] + 256 * [int]$bytes[$offset + 1]
                if ($unsigned -ge 32768) { $unsigned -= 65536 }
                $unsigned
            }
            $lines.Add('        ' + ($values -join ', ') + ',')
        }
        $lines.Add('    }},')
    }
} finally { $zip.Dispose() }
$lines.Add('}};')
$lines.Add('} // namespace ahq::audio::data')
[IO.File]::WriteAllLines((Join-Path (Get-Location) $Output), $lines, [Text.UTF8Encoding]::new($false))
