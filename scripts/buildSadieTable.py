"""Extract the median-plane SADIE II D1 HRIRs. Requires numpy and h5py for regeneration only."""
import hashlib
import sys
from pathlib import Path

import h5py
import numpy as np

source = Path(sys.argv[1])
expected = "9af7cb19531e52fb7ae8ec92621e6ab62b1d5fe584b3742be36699a0ddb0ccd4"
if hashlib.sha256(source.read_bytes()).hexdigest() != expected:
    raise SystemExit("Unexpected SOFA source; use the documented SADIE II V2-1 D1 48 kHz file.")
elevations = [-90, -81, -75, -60, -45, -30, -15, 0, 15, 30, 45, 60, 75, 90]
with h5py.File(source) as data:
    positions, impulses = data["SourcePosition"][:], data["Data.IR"][:]
    selected = []
    for angle in elevations:
        matches = np.where((positions[:, 0] == 0) & (positions[:, 1] == angle))[0]
        if len(matches) != 1:
            raise SystemExit(f"Expected exactly one frontal measurement at elevation {angle}")
        selected.append(impulses[matches[0]].astype(np.float32))

output = Path(__file__).resolve().parents[1] / "src/spatial/data/sadieElevation.h"
with output.open("w", encoding="utf-8", newline="\n") as file:
    file.write("""// Derived from SADIE II V2-1, D1 KU100, 48 kHz, 256-tap diffuse-field HRIRs.
// Copyright 2018 University of York. Apache-2.0; see sadieAttribution.md and sadieLicense.txt.
// The -90 degree source response is interpolated by the dataset authors, not directly measured.
// Generated by scripts/buildSadieTable.py. Only azimuth zero is retained. Samples are float32.
#pragma once
#include <array>
namespace ahq::audio::data {
inline constexpr std::array<float, 14> SADIE_ELEVATIONS{""")
    file.write(", ".join(f"{v}.F" for v in elevations) + "};\n")
    file.write("inline constexpr float SADIE_ELEVATION[14][2][256] = {\n")
    for response in selected:
        file.write("    {\n")
        for ear in response:
            file.write("        {\n")
            for offset in range(0, 256, 8):
                file.write("            " + ", ".join(f"{float(v):.9e}F" for v in ear[offset:offset+8]) + ",\n")
            file.write("        },\n")
        file.write("    },\n")
    file.write("};\n} // namespace ahq::audio::data\n")
